(() => {
  const root = document.documentElement;
  const textEls = [...document.querySelectorAll('[data-i18n]')];
  const attrEls = [...document.querySelectorAll('[data-i18n-attr]')];

  // Remember the English originals straight from the HTML
  textEls.forEach((el) => { el.dataset.i18nEn = el.innerHTML; });
  attrEls.forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr] = pair.split(':');
      el.setAttribute(`data-en-${attr}`, el.getAttribute(attr) ?? '');
    });
  });

  let current = 'en';

  const t = (key) => STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;

  const apply = (lang) => {
    current = lang === 'sl' ? 'sl' : 'en';
    const dict = STRINGS[current];

    textEls.forEach((el) => {
      const key = el.dataset.i18n;
      el.innerHTML = current === 'en' ? el.dataset.i18nEn : (dict[key] ?? el.dataset.i18nEn);
    });
    attrEls.forEach((el) => {
      el.dataset.i18nAttr.split(';').forEach((pair) => {
        const [attr, key] = pair.split(':');
        const en = el.getAttribute(`data-en-${attr}`);
        el.setAttribute(attr, current === 'en' ? en : (dict[key] ?? en));
      });
    });

    root.lang = current;
    document.querySelectorAll('.lang__btn').forEach((b) => {
      b.setAttribute('aria-pressed', String(b.dataset.lang === current));
    });
    const langField = document.querySelector('#contact-form [name="language"]');
    if (langField) langField.value = current;

    try { localStorage.setItem('hw-lang', current); } catch (e) { /* storage unavailable */ }
    root.classList.remove('lang-pending');
    document.dispatchEvent(new CustomEvent('langchange', { detail: current }));
  };

  // Initial language: ?lang= in URL, then saved choice, otherwise English
  const fromUrl = new URLSearchParams(location.search).get('lang');
  let saved = null;
  try { saved = localStorage.getItem('hw-lang'); } catch (e) { /* ignore */ }
  apply(fromUrl === 'sl' || fromUrl === 'en' ? fromUrl : saved === 'sl' ? 'sl' : 'en');

  document.querySelectorAll('.lang__btn').forEach((b) => {
    b.addEventListener('click', () => {
      apply(b.dataset.lang);
      // Keep the URL shareable without reloading
      const url = new URL(location.href);
      if (current === 'en') url.searchParams.delete('lang'); else url.searchParams.set('lang', current);
      history.replaceState(null, '', url);
    });
  });

  window.HW = { t, get lang() { return current; } };
})();
